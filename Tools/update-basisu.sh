#!/usr/bin/env bash
# Vendor basis_universal into Source/ThirdParty/basis_universal, unmodified, and regenerate the
# per-file wrapper translation units the UE modules compile it through.
#
#   Tools/update-basisu.sh <tag-or-commit> [--repo <url-or-path>]   re-vendor from upstream
#   Tools/update-basisu.sh --check [--repo <url-or-path>]           verify the vendored tree is
#                                                                   byte-identical to the recorded commit
#
# The vendored tree is never edited by hand: anything UE needs (PCH isolation, warning levels,
# zstd sharing) is done from the Build.cs files, the wrappers and BasisUniversalBegin.h/End.h
# beside the tree, so an upgrade is this script plus a test run.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VENDOR="$ROOT/Source/ThirdParty/basis_universal"
VERSION_FILE="$ROOT/Source/ThirdParty/basis_universal.version"
REPO="https://github.com/BinomialLLC/basis_universal.git"
REF=""
CHECK=0

while [ $# -gt 0 ]; do
	case "$1" in
		--repo) REPO="$2"; shift 2 ;;
		--check) CHECK=1; shift ;;
		-h|--help) sed -n '2,12p' "$0"; exit 0 ;;
		*) REF="$1"; shift ;;
	esac
done

# What gets vendored. Everything else upstream (tools, examples, web and python bindings, test
# images) is not needed to build the library.
VENDORED_PATHS="LICENSE NOTICE LICENSES encoder transcoder zstd"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

fetch() {
	git clone --quiet --no-checkout "$REPO" "$TMP/src"
	git -C "$TMP/src" -c advice.detachedHead=false checkout --quiet "$1"
}

if [ "$CHECK" = 1 ]; then
	[ -f "$VERSION_FILE" ] || { echo "no $VERSION_FILE; nothing to check" >&2; exit 1; }
	COMMIT="$(sed -n 2p "$VERSION_FILE")"
	fetch "$COMMIT"
	STATUS=0
	for P in $VENDORED_PATHS; do
		diff -r "$TMP/src/$P" "$VENDOR/$P" || STATUS=1
	done
	if [ "$STATUS" = 0 ]; then
		echo "Source/ThirdParty/basis_universal matches upstream $COMMIT"
	else
		echo "Source/ThirdParty/basis_universal differs from upstream $COMMIT" >&2
	fi
	exit "$STATUS"
fi

[ -n "$REF" ] || { echo "usage: $0 <tag-or-commit> [--repo <url-or-path>] | --check" >&2; exit 2; }

fetch "$REF"
COMMIT="$(git -C "$TMP/src" rev-parse HEAD)"

rm -rf "$VENDOR"
mkdir -p "$VENDOR"
for P in $VENDORED_PATHS; do
	cp -R "$TMP/src/$P" "$VENDOR/$P"
done
printf '%s\n%s\n' "$REF" "$COMMIT" > "$VERSION_FILE"

# The encoder sources upstream builds into its library, read from its own CMake list so a new or
# removed file upstream is picked up rather than silently skipped. The optional Android ASTC
# decoder (a second decoder used only for validation) and astcenc are deliberately left out.
ENCODER_SOURCES="$(awk '
	/set\(ENCODER_LIB_SRC_LIST/ { inlist = 1; next }
	inlist && /\)/ { exit }
	inlist { gsub(/[ \t\r]/, ""); if ($0 ~ /^encoder\/[^\/]*\.cpp$/) print }
' "$TMP/src/CMakeLists.txt")"
[ -n "$ENCODER_SOURCES" ] || { echo "could not read ENCODER_LIB_SRC_LIST from upstream CMakeLists.txt" >&2; exit 1; }

# Each vendored source is compiled between BasisUniversalBegin.h (library configuration, warnings
# silenced) and BasisUniversalEnd.h.
include_lines() { # <vendored source>
	echo "#include \"BasisUniversalBegin.h\""
	echo "#include \"$1\""
	echo "#include \"BasisUniversalEnd.h\""
}

write_wrapper() { # <dest file> <vendored source> [guard macro]
	local DEST="$1" SRC="$2" GUARD="${3:-}"
	{
		echo "// Generated by Tools/update-basisu.sh; do not edit."
		echo "// Compiles Source/ThirdParty/basis_universal/$SRC as its own translation unit (upstream relies on"
		echo "// file-scoped using-directives, so these must never be merged into one unity file)."
		if [ -n "$GUARD" ]; then
			echo "#if $GUARD"
			include_lines "$SRC"
			echo "#else"
			echo "typedef int BasisUniversalEmptyTranslationUnit;"
			echo "#endif"
		else
			include_lines "$SRC"
		fi
	} > "$DEST"
}

ENC_WRAP="$ROOT/Source/TextureFormatBasis/Private/BasisUniversal"
RT_WRAP="$ROOT/Source/BasisTranscoder/Private/BasisUniversal"
rm -rf "$ENC_WRAP" "$RT_WRAP"
mkdir -p "$ENC_WRAP" "$RT_WRAP"

for SRC in $ENCODER_SOURCES; do
	write_wrapper "$ENC_WRAP/$(basename "$SRC")" "$SRC"
done

# The transcoder and zstd are compiled by both modules in a modular build (each binary needs its
# own copy, since upstream exports nothing) and only by BasisTranscoder in a monolithic one;
# BasisTranscoder.Build.cs sets the guards.
write_wrapper "$ENC_WRAP/basisu_transcoder.cpp" "transcoder/basisu_transcoder.cpp" "BASIS_UE_ENCODER_TRANSCODER"
write_wrapper "$ENC_WRAP/zstd.c" "zstd/zstd.c" "BASIS_UE_ENCODER_ZSTD"
write_wrapper "$RT_WRAP/basisu_transcoder.cpp" "transcoder/basisu_transcoder.cpp"
{
	echo "// Generated by Tools/update-basisu.sh; do not edit."
	echo "// zstd for the transcoder: decoder only, the full library when this module also carries the encoder's"
	echo "// copy (monolithic targets that include the editor), or nothing when ZstdModule names an external zstd."
	echo "#if BASIS_UE_ZSTD_SOURCE == 1"
	include_lines "zstd/zstddeclib.c"
	echo "#elif BASIS_UE_ZSTD_SOURCE == 2"
	include_lines "zstd/zstd.c"
	echo "#else"
	echo "typedef int BasisUniversalEmptyTranslationUnit;"
	echo "#endif"
} > "$RT_WRAP/zstd.c"

echo "Vendored basis_universal $REF ($COMMIT)"
echo "Encoder sources: $(echo "$ENCODER_SOURCES" | wc -l | tr -d ' ')"
echo "Next: build and run Tests/ (see README). The library's version string is in the cache keys; if it"
echo "did not change but the output did, bump FormatVersion in TextureFormatBasis.cpp."
